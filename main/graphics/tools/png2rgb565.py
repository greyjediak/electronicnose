"""
png2rgb565.py -- convert Figma PNG exports into a C header for the TFT.

Usage (from the electronicnose/ folder):
    python main/graphics/tools/png2rgb565.py --bg 0C0E17

Reads every *.png in main/graphics/assets/ and writes main/graphics/images.h:
one RGB565 array per image plus an IMAGES[] table that gfx::image(name) searches.

Naming (an "enose_" prefix on the file name is ignored):
  menu.png                 -> "menu"     full image, centered on the screen
  splash1.png ... splash5.png  (an animation: same size, numbered from 1)
                           -> "splash"   frame 1 as the full background
                           -> "splash1".."splash5": ONLY the rectangle that
                              changes between frames, with its x/y on screen.
  So an animation costs one full screen plus a few small crops, not N screens.

Export from Figma at 1x, at the exact screen size (240x240), background fill on.
Transparent pixels are blended onto --bg (match TFT_BG_COLOR in display_config.h).

Flash budget: a full 240x240 image is ~113 KB; the XIAO has ~790 KB for the program.

Requires: pip install pillow
"""

import argparse
import re
from collections import defaultdict
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SKETCH_DIR = HERE.parent
STRIP_PREFIX = "enose_"


def to_rgb565(img: Image.Image, bg: tuple) -> list:
    img = img.convert("RGBA")
    base = Image.new("RGBA", img.size, bg + (255,))
    base.alpha_composite(img)
    raw = base.tobytes()  # RGBA, 4 bytes per pixel
    return [((raw[i] & 0xF8) << 8) | ((raw[i + 1] & 0xFC) << 3) | (raw[i + 2] >> 3)
            for i in range(0, len(raw), 4)]


def crop(px: list, w: int, box: tuple) -> list:
    x0, y0, x1, y1 = box
    return [px[y * w + x] for y in range(y0, y1) for x in range(x0, x1)]


def diff_box(frames: list, w: int, h: int):
    """Smallest rectangle containing every pixel that differs from frame 0."""
    first = frames[0]
    xs, ys = [], []
    for px in frames[1:]:
        for i, (a, b) in enumerate(zip(first, px)):
            if a != b:
                xs.append(i % w)
                ys.append(i // w)
    if not xs:
        return None
    return (min(xs), min(ys), max(xs) + 1, max(ys) + 1)


def logical_name(path: Path) -> str:
    stem = path.stem.lower()
    if stem.startswith(STRIP_PREFIX):
        stem = stem[len(STRIP_PREFIX):]
    return stem


def ident(name: str) -> str:
    return "img_" + re.sub(r"[^0-9a-zA-Z_]", "_", name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--assets", default=SKETCH_DIR / "assets", type=Path)
    ap.add_argument("--out", default=SKETCH_DIR / "images.h", type=Path)
    ap.add_argument("--bg", default="0C0E17", help="hex RGB for transparent pixels")
    ap.add_argument("--screen", default="240x240", help="screen size WxH, for centering")
    args = ap.parse_args()

    bg = tuple(int(args.bg[i:i + 2], 16) for i in (0, 2, 4))
    sw, sh = (int(v) for v in args.screen.lower().split("x"))

    # Split files into animations (name + number) and single images.
    singles, groups = [], defaultdict(dict)
    for p in sorted(args.assets.glob("*.png")):
        name = logical_name(p)
        m = re.fullmatch(r"(.*?)(\d+)", name)
        if m:
            groups[m.group(1)][int(m.group(2))] = p
        else:
            singles.append((name, p))
    for base, frames in list(groups.items()):     # a lone numbered file is just an image
        if len(frames) < 2:
            (n, p), = frames.items()
            singles.append((f"{base}{n}", p))
            del groups[base]

    entries = []   # (name, x, y, w, h, pixels, note)

    for name, p in singles:
        img = Image.open(p)
        w, h = img.size
        entries.append((name, (sw - w) // 2, (sh - h) // 2, w, h, to_rgb565(img, bg), p.name))

    for base, frames in sorted(groups.items()):
        nums = sorted(frames)
        imgs = [Image.open(frames[n]) for n in nums]
        w, h = imgs[0].size
        if any(i.size != (w, h) for i in imgs):
            raise SystemExit(f"{base}: all animation frames must be the same size")
        pxs = [to_rgb565(i, bg) for i in imgs]
        ox, oy = (sw - w) // 2, (sh - h) // 2
        entries.append((base, ox, oy, w, h, pxs[0], f"{frames[nums[0]].name} (background)"))
        box = diff_box(pxs, w, h)
        if box is None:
            print(f"  {base}: frames are identical, keeping only the background")
            continue
        x0, y0, x1, y1 = box
        for n, px in zip(nums, pxs):
            entries.append((f"{base}{n}", ox + x0, oy + y0, x1 - x0, y1 - y0,
                            crop(px, w, box), f"{frames[n].name} (changed area only)"))

    lines = [
        "// AUTO-GENERATED by tools/png2rgb565.py -- do not edit by hand.",
        "// Re-run the script after changing anything in assets/.",
        "#ifndef IMAGES_H",
        "#define IMAGES_H",
        "#include <Arduino.h>",
        "",
        "struct ImageAsset {",
        "    const char*     name;",
        "    int16_t         x, y;   // where it goes on the screen",
        "    uint16_t        w, h;",
        "    const uint16_t* data;   // RGB565, row-major",
        "};",
        "",
    ]
    table, total = [], 0
    for name, x, y, w, h, px, note in entries:
        total += len(px) * 2
        lines.append(f"// {note}  {w}x{h} at ({x},{y})  {len(px) * 2} bytes")
        lines.append(f"const uint16_t {ident(name)}[{len(px)}] PROGMEM = {{")
        for i in range(0, len(px), 12):
            lines.append("    " + ", ".join(f"0x{v:04X}" for v in px[i:i + 12]) + ",")
        lines.append("};")
        lines.append("")
        table.append(f'    {{ "{name}", {x}, {y}, {w}, {h}, {ident(name)} }},')
        print(f"  {name:16s} {w:3d}x{h:<3d} at ({x},{y})   <- {note}")

    lines.append(f"static const uint8_t IMAGE_COUNT = {len(table)};")
    if table:
        lines.append("static const ImageAsset IMAGES[] = {")
        lines.extend(table)
        lines.append("};")
    else:
        lines.append("static const ImageAsset* const IMAGES = nullptr;  // no PNGs in assets/ yet")
    lines.append("")
    lines.append("#endif")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {args.out} : {len(table)} image(s), {total / 1024:.1f} KB of flash")


if __name__ == "__main__":
    main()
